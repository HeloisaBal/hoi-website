import { defineArrayMember, defineField, defineType } from 'sanity'
import { FAQ_LIMITS } from '../../lib/chat/limits'
import { text, words } from './fields'

/* ------------------------------------------------------------
   Chatbot: the "Ask hoi" assistant in the bottom-right corner.
   It already knows everything else on the website (events,
   programmes, team, contact details). The questions and answers
   below are for what the website doesn't say, e.g. details about
   an offer. Visitors can also send hoi a message through it;
   those arrive at the address under "Contact & links".
   ------------------------------------------------------------ */

export const chatbot = defineType({
  name: 'chatbot', title: 'Chatbot', type: 'document',
  groups: [
    { name: 'knowledge', title: 'What the bot knows', default: true },
    { name: 'texts', title: 'Texts' },
  ],
  fieldsets: [{ name: 'labels', title: 'Small labels', options: { collapsible: true, collapsed: true } }],
  fields: [
    defineField({
      name: 'enabled', title: 'Show the chatbot on the website', type: 'boolean', group: 'texts',
      initialValue: true,
    }),
    defineField({
      name: 'faq', title: 'Questions and answers', type: 'array', group: 'knowledge',
      description:
        'The bot already reads the whole website. Add what the website doesn’t say: who an offer is for, how to apply, what it costs, ' +
        'how long it takes. Write one clear question and a complete answer. The bot uses these to answer, in English or German.',
      of: [defineArrayMember({
        type: 'object', name: 'qa',
        fields: [
          defineField({
            name: 'question', title: 'Question', type: 'string',
            description: `e.g. "Who can apply to the Venture Studio?" Max ${FAQ_LIMITS.question} characters.`,
            validation: (r) => r.required().max(FAQ_LIMITS.question),
          }),
          defineField({
            name: 'answer', title: 'Answer', type: 'text', rows: 4,
            description: `Plain text. You can include a link ("https://…"). Max ${FAQ_LIMITS.answer} characters.`,
            validation: (r) => r.required().max(FAQ_LIMITS.answer),
          }),
        ],
        preview: { select: { title: 'question', subtitle: 'answer' } },
      })],
      validation: (r) => r.max(FAQ_LIMITS.count),
    }),
    text('buttonLabel', 'Button label', 20, { group: 'texts', description: 'The round button in the corner, e.g. "Ask hoi".' }),
    text('title', 'Title of the chat window', 30, { group: 'texts' }),
    text('greeting', 'First message', 220, { group: 'texts', rows: 3, description: 'What the bot says when a visitor opens the chat.' }),
    words('suggestions', 'Suggested questions', 4, 60, {
      group: 'texts', description: 'Up to 4 questions visitors can tap to start. Max 60 characters each.',
    }),
    text('placeholder', 'Hint in the message box', 40, { group: 'texts' }),
    text('disclaimer', 'Small note under the chat', 120, {
      group: 'texts', description: 'e.g. that answers are generated by AI and can be wrong.',
    }),
    text('contactIntro', 'Contact form: text above it', 160, { group: 'texts', rows: 2 }),
    text('contactPrivacy', 'Contact form: privacy note', 200, {
      group: 'texts', rows: 2, description: 'Shown next to the send button. Mention what happens with the message.',
    }),
    text('contactThanks', 'Contact form: thank-you message', 160, { group: 'texts', rows: 2 }),
    ...([
      ['contactButton', 'Button that opens the contact form', 24],
      ['nameLabel', 'Contact form: name label', 20],
      ['emailLabel', 'Contact form: email label', 20],
      ['messageLabel', 'Contact form: message label', 20],
      ['sendLabel', 'Send button', 16],
      ['checkText', 'Contact form: when a field is wrong', 30],
      ['errorText', 'When something goes wrong', 140],
      ['busyText', 'When a visitor sends too many messages', 140],
    ] as const).map(([name, title, max]) => ({ ...text(name, title, max, { group: 'texts' }), fieldset: 'labels' })),
  ],
  preview: { prepare: () => ({ title: 'Chatbot' }) },
})
